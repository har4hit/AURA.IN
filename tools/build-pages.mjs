// Builds the SEO layer from projects-data.js:
//   - work/<id>.html, one crawlable page per project
//   - the <head> SEO block of index.html (between the SEO:START / SEO:END markers)
//   - sitemap.xml
// Run after editing projects-data.js:  npm run build:pages
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const { PROJECTS, projectHTML, escHTML: esc } = createRequire(import.meta.url)(join(ROOT, 'projects-data.js'));

const SITE = 'https://aurain.netlify.app';
const FOUNDER = { name: 'Harshit Jangid', handle: 'har4hit' };
const SAME_AS = [
  'https://github.com/har4hit',
  'https://www.youtube.com/@har4hit',
  'https://www.instagram.com/har4hit',
  'https://www.linkedin.com/in/har4hit',
];
const TODAY = new Date().toISOString().slice(0, 10);
const ids = Object.keys(PROJECTS);
const pageUrl = id => `${SITE}/work/${id}.html`;

const ORG = {
  '@type': 'Organization',
  '@id': `${SITE}/#organization`,
  name: 'Aura',
  alternateName: ['aura.in', 'Aura in', 'Aurain', 'Aura Studio'],
  url: `${SITE}/`,
  logo: { '@type': 'ImageObject', url: `${SITE}/IMG/icon.png`, width: 512, height: 512 },
  description: 'Aura (aura.in) is an app, game and software studio in India founded by Harshit Jangid (har4hit).',
  founder: { '@id': `${SITE}/#founder` },
  email: 'oneaura.in@gmail.com',
  areaServed: 'Worldwide',
  address: { '@type': 'PostalAddress', addressCountry: 'IN' },
  knowsAbout: ['Mobile app development', 'Game development', 'Unity', 'React Native', 'Custom software', 'ERP software', 'AI tools'],
  sameAs: SAME_AS,
};
const PERSON = {
  '@type': 'Person',
  '@id': `${SITE}/#founder`,
  name: FOUNDER.name,
  alternateName: FOUNDER.handle,
  jobTitle: 'Founder of Aura',
  worksFor: { '@id': `${SITE}/#organization` },
  nationality: { '@type': 'Country', name: 'India' },
  knowsAbout: ['App development', 'Game development', 'Unity', 'React Native', 'Node.js', 'Supabase'],
  url: `${SITE}/`,
  sameAs: SAME_AS,
};
const WEBSITE = {
  '@type': 'WebSite',
  '@id': `${SITE}/#website`,
  name: 'Aura',
  alternateName: ['aura.in', 'Aurain'],
  url: `${SITE}/`,
  publisher: { '@id': `${SITE}/#organization` },
  inLanguage: 'en',
};

// The app itself, as schema.org describes it. Only facts shown on the page; no ratings or prices.
function appEntity(id) {
  const p = PROJECTS[id];
  return {
    '@type': p.seo.type,
    '@id': `${pageUrl(id)}#app`,
    name: p.title,
    description: p.seo.description,
    url: pageUrl(id),
    image: `${SITE}/${p.logo}`,
    applicationCategory: p.seo.category,
    ...(p.seo.os && { operatingSystem: p.seo.os }),
    ...(p.seo.type === 'VideoGame' && { gamePlatform: 'Mobile', genre: 'Horror' }),
    dateCreated: p.facts.Year,
    author: { '@id': `${SITE}/#organization` },
    creator: { '@id': `${SITE}/#founder` },
    keywords: p.stack.join(', '),
  };
}

const jsonld = graph => `<script type="application/ld+json">\n${JSON.stringify({ '@context': 'https://schema.org', '@graph': graph }, null, 2)}\n  </script>`;

function headTags({ title, description, url, image, imageAlt, type = 'website' }) {
  return `<title>${esc(title)}</title>
  <meta name="description" content="${esc(description)}" />
  <meta name="author" content="${FOUNDER.name} (${FOUNDER.handle})" />
  <meta name="robots" content="index, follow, max-image-preview:large" />
  <link rel="canonical" href="${url}" />
  <meta property="og:type" content="${type}" />
  <meta property="og:site_name" content="Aura" />
  <meta property="og:url" content="${url}" />
  <meta property="og:title" content="${esc(title)}" />
  <meta property="og:description" content="${esc(description)}" />
  <meta property="og:image" content="${image}" />
  <meta property="og:image:alt" content="${esc(imageAlt)}" />
  <meta property="og:locale" content="en_IN" />
  <meta name="twitter:card" content="summary_large_image" />
  <meta name="twitter:title" content="${esc(title)}" />
  <meta name="twitter:description" content="${esc(description)}" />
  <meta name="twitter:image" content="${image}" />`;
}

/* ---------- index.html head ---------- */
let index = readFileSync(join(ROOT, 'index.html'), 'utf8');
const homeHead = `<!-- SEO:START (generated by tools/build-pages.mjs — edit there) -->
  ${headTags({
    title: 'Aura (aura.in) — App & Game Studio by Harshit Jangid (har4hit)',
    description: `Aura (aura.in) is an app and game studio in India founded by Harshit Jangid (har4hit). Makers of ${ids.map(i => PROJECTS[i].title).join(', ').replace(/, ([^,]*)$/, ' and $1')}.`,
    url: `${SITE}/`,
    image: `${SITE}/IMG/og.jpg`,
    imageAlt: 'Aura: apps, games and software. A glowing particle phone on black.',
  })}
  ${jsonld([
    ORG, PERSON, WEBSITE,
    {
      '@type': 'ItemList',
      '@id': `${SITE}/#work`,
      name: 'Apps, games and software by Aura',
      itemListElement: ids.map((id, i) => ({ '@type': 'ListItem', position: i + 1, url: pageUrl(id), name: PROJECTS[id].title })),
    },
  ])}
  <!-- SEO:END -->`;
index = index.replace(/<!-- SEO:START[\s\S]*?<!-- SEO:END -->/, homeHead);
writeFileSync(join(ROOT, 'index.html'), index);

/* ---------- work/<id>.html ---------- */
// Nav and footer come from index.html, with its in-page links pointed back at the home page.
const between = (a, b) => index.slice(index.indexOf(a), index.indexOf(b));
const home = s => s.replace(/href="#([^"]*)"/g, (m, h) => `href="../index.html${h && h !== 'hero' ? '#' + h : ''}"`)
  .replace(/href="work\//g, 'href="').replace(/src="IMG\//g, 'src="../IMG/');
const nav = home(between('  <!-- NAVBAR -->', '  <main>'));
const footer = home(between('  <!-- FOOTER -->', '  <!-- PROJECT DETAIL'));

mkdirSync(join(ROOT, 'work'), { recursive: true });
for (const id of ids) {
  const p = PROJECTS[id];
  const html = `<!DOCTYPE html>
<html lang="en">

<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <!-- generated by tools/build-pages.mjs from projects-data.js — edit there, then run npm run build:pages -->
  ${headTags({
    title: `${p.title} — ${p.seo.title} by Aura (aura.in)`,
    description: p.seo.description,
    url: pageUrl(id),
    image: `${SITE}/${p.logo}`,
    imageAlt: `${p.title} logo`,
    type: 'article',
  })}
  <link rel="icon" type="image/png" href="../IMG/icon.png" />
  <link rel="apple-touch-icon" href="../IMG/icon.png" />
  ${jsonld([
    appEntity(id),
    {
      '@type': 'WebPage',
      '@id': pageUrl(id),
      url: pageUrl(id),
      name: `${p.title} — ${p.seo.title} by Aura`,
      isPartOf: { '@id': `${SITE}/#website` },
      about: { '@id': `${pageUrl(id)}#app` },
      breadcrumb: { '@id': `${pageUrl(id)}#breadcrumb` },
    },
    {
      '@type': 'BreadcrumbList',
      '@id': `${pageUrl(id)}#breadcrumb`,
      itemListElement: [
        { '@type': 'ListItem', position: 1, name: 'Aura', item: `${SITE}/` },
        { '@type': 'ListItem', position: 2, name: 'Work', item: `${SITE}/#work` },
        { '@type': 'ListItem', position: 3, name: p.title, item: pageUrl(id) },
      ],
    },
    { '@type': 'Organization', '@id': `${SITE}/#organization`, name: 'Aura', url: `${SITE}/` },
    { '@type': 'Person', '@id': `${SITE}/#founder`, name: FOUNDER.name, alternateName: FOUNDER.handle },
  ])}
  <link rel="preconnect" href="https://fonts.googleapis.com" />
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
  <link href="https://fonts.googleapis.com/css2?family=Archivo:wdth,wght@62..125,300..900&display=swap" rel="stylesheet" />
  <link rel="stylesheet" href="../style.css" />
  <script defer data-domain="aura.in" src="https://plausible.io/js/script.js"></script>
</head>

<body class="work-page">

${nav}  <main class="wp">
    <div class="pd-body">
      <nav class="crumbs" aria-label="Breadcrumb"><a href="../index.html">Aura</a> / <a href="../index.html#work">Work</a> / <span aria-current="page">${esc(p.title)}</span></nav>
${projectHTML(id, { heading: 'h1', base: '../', nextHref: n => `${n}.html` })}
    </div>
  </main>

${footer}  <script src="../main.js" defer></script>
</body>

</html>
`;
  writeFileSync(join(ROOT, 'work', `${id}.html`), html);
}

/* ---------- sitemap.xml ---------- */
const img = (loc, title) => `\n    <image:image>\n      <image:loc>${loc}</image:loc>\n      <image:title>${esc(title)}</image:title>\n    </image:image>`;
writeFileSync(join(ROOT, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
  <url>
    <loc>${SITE}/</loc>
    <lastmod>${TODAY}</lastmod>${img(`${SITE}/IMG/og.jpg`, 'Aura — apps, games and software')}${img(`${SITE}/IMG/icon.png`, 'Aura logo')}
  </url>
${ids.map(id => `  <url>
    <loc>${pageUrl(id)}</loc>
    <lastmod>${TODAY}</lastmod>${[PROJECTS[id].logo, ...PROJECTS[id].images.map(i => i.src)].filter((v, i, a) => a.indexOf(v) === i).map(src => img(`${SITE}/${src}`, PROJECTS[id].title)).join('')}
  </url>`).join('\n')}
</urlset>
`);

console.log(`built ${ids.length} project pages, index head and sitemap.xml`);
